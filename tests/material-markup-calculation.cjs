const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const rows=[{qty:2,unitPrice:100,markupPercent:50,name:'Percentage',unit:'st'},{qty:1,unitPrice:80,customerUnitPrice:70,name:'Fixed',unit:'st'}];
const context={toNumber:(v,f)=>Number.isFinite(Number(v))?Number(v):f,usedMats:()=>rows,clean:v=>String(v)};
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('function materialSellingUnitPrice('),html.indexOf('function quoteMaterialTotals(')),context);
const totals=context.calculateMaterialTotals(rows,25);
assert.equal(totals.cost,280);assert.equal(totals.total,370);assert.equal(totals.markupSum,90);
assert.equal(context.calculateMaterialTotals(rows,70).total,370,'Specific prices override general markup');
assert.equal(context.materialSellingUnitPrice({unitPrice:100,markupPercent:0},25),100);
assert.equal(context.materialSellingUnitPrice({unitPrice:100,customerUnitPrice:0},25),0);
const exporter=fs.readFileSync('export-v59.js','utf8');
vm.runInContext(exporter.slice(exporter.indexOf('function internalRows('),exporter.indexOf('function makePdf(')),context);
const exported=context.internalRows({markupPercent:25});
assert.equal(exported[0]['Kundpris/st'],150);assert.equal(exported[1]['Kundpris/st'],70);
assert.equal(exported.reduce((n,r)=>n+r['Försäljning totalt'],0),370,'Export agrees with app totals');
assert.equal(exported.reduce((n,r)=>n+r.Materialvinst,0),90);
console.log('Markup calculation and actual export rows OK: purchase cost, markup, fixed price, zero and totals');
